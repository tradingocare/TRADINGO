const pwPath = require('path').resolve(__dirname, '..', 'node_modules', '.pnpm', 'playwright@1.61.0', 'node_modules', 'playwright');
const { chromium } = require(pwPath);
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
  const errors = [];
  page.on('pageerror', err => errors.push(err.message));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(`[console] ${msg.text()}`); });
  await page.goto('http://localhost:3000/products/arduino-mega-2560-r3-1784561335498', { waitUntil: 'load', timeout: 30000 });
  await page.waitForTimeout(8000);
  const text = await page.evaluate(() => document.body.innerText.substring(0, 3000));
  const hasError = text.includes('Something went wrong');
  console.log(`Error boundary: ${hasError}`);
  console.log(`Runtime errors: ${errors.length}`);
  errors.forEach(e => console.log(`  ${e}`));
  console.log('--- PAGE TEXT ---');
  console.log(text);
  await page.screenshot({ path: 'E:/tradingo/screenshots/audit-product-detail.png', fullPage: true });
  await browser.close();
})();
